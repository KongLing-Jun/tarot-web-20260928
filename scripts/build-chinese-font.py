"""Build local, on-demand Chinese WenKai shards.

Usage: python scripts/build-chinese-font.py SOURCE_DIRECTORY
Requires fonttools and brotli (build tools only). Sources are the official
LXGWWenKai-Light.ttf and LXGWWenKai-Regular.ttf from release v1.522:
https://github.com/lxgw/LxgwWenKai/releases/tag/v1.522
License: public/brand/home-wenkai-OFL.txt. Latin stays in the existing fonts.
"""
import hashlib
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    'Light': (300, '526ec70cbb0118e871d481f8179e03ff045f0e4d72d080dcca87950c4ab27cca'),
    'Regular': (400, '39ad71264b588165b469e35e6afb162a378dacd1f95348160240ba9038ac3009'),
}


def chinese(code):
    return any(start <= code <= end for start, end in (
        (0x2E80, 0x2FDF), (0x3000, 0x303F), (0x3100, 0x312F),
        (0x31A0, 0x31BF), (0x3400, 0x4DBF), (0x4E00, 0x9FFF),
        (0xF900, 0xFAFF), (0xFE10, 0xFE1F), (0xFE30, 0xFE4F),
        (0xFF01, 0xFF60), (0xFFE0, 0xFFE6), (0x20000, 0x323AF),
    ))


def unicode_ranges(codes):
    ranges = []
    for code in sorted(codes):
        if ranges and code == ranges[-1][1] + 1:
            ranges[-1][1] = code
        else:
            ranges.append([code, code])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in ranges)


if len(sys.argv) != 2:
    raise SystemExit(__doc__)

text = ''.join(path.read_text(encoding='utf-8')
               for directory in ('app', 'components', 'lib')
               for path in (ROOT / directory).rglob('*')
               if path.suffix in ('.ts', '.tsx'))
ui_codes = {ord(char) for char in text if chinese(ord(char))}
output = ROOT / 'public/brand/wenkai'
output.mkdir(parents=True, exist_ok=True)
css = ['/* Generated by scripts/build-chinese-font.py; LXGW WenKai v1.522, OFL-1.1. */']
for name, (weight, digest) in SOURCES.items():
    source = Path(sys.argv[1]) / f'LXGWWenKai-{name}.ttf'
    if hashlib.sha256(source.read_bytes()).hexdigest() != digest:
        raise ValueError(f'Unexpected font source: {source}')
    coverage = {code for code in TTFont(source).getBestCmap() if chinese(code)}
    missing = ui_codes - coverage
    if missing:
        raise ValueError(f'Chinese source characters missing: {unicode_ranges(missing)}')
    common = sorted(ui_codes)
    remaining = sorted(coverage - ui_codes)
    # All existing UI text loads together; other Chinese loads only when used.
    groups = [('ui', common)] + [(f'{i // 512:03}', remaining[i:i + 512])
                                 for i in range(0, len(remaining), 512)]
    for label, codes in groups:
        font = TTFont(source)
        options = subset.Options()
        options.flavor = 'woff2'
        worker = subset.Subsetter(options=options)
        worker.populate(unicodes=codes)
        worker.subset(font)
        font.flavor = 'woff2'
        filename = f'{name.lower()}-{label}.woff2'
        font.save(output / filename)
        # Verify the actual binary, not just the requested Unicode range.
        if not set(codes) <= set(TTFont(output / filename).getBestCmap()):
            raise ValueError(f'Incomplete subset: {filename}')
        css.append(
            '@font-face {\n'
            '  font-family: "Tarot WenKai Chinese";\n'
            f'  src: url("/brand/wenkai/{filename}") format("woff2");\n'
            f'  font-weight: {weight};\n'
            '  font-style: normal;\n'
            '  font-display: swap;\n'
            f'  unicode-range: {unicode_ranges(codes)};\n'
            '}')
    print(f'{name}: {len(coverage)} Chinese code points, {len(groups)} shards, {len(common)} UI characters')
(ROOT / 'app/_styles/chinese-font.css').write_text('\n\n'.join(css) + '\n', encoding='utf-8')
